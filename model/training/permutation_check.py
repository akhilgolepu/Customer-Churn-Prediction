"""Why does a model trained on permuted labels not score AUC 0.5?

The degraded demo candidate (trained on shuffled labels) scores ROC-AUC 0.64
against the true test labels. This script tests the explanation that such a
model learns nothing about churn but is still a random function of strongly
predictive features, so its scores can correlate with churn by accident:

  1. Train the production recipe on N independent label permutations
     (fit on train, early-stop on validation, both permuted).
  2. Score the test split; record AUC against the TRUE labels, and the
     Spearman correlation of the scores with the shipped model's scores.
  3. Control: the same test scores, but randomly re-assigned to rows. That is
     what "scores independent of the labels" looks like.

If the explanation holds, (1) spreads far wider than the control, centred on
0.5, and |AUC - 0.5| tracks |correlation with the real model|.

Writes docs/permutation_check.json and docs/permutation_check.md.

Usage:
    python model/training/permutation_check.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr
from sklearn.metrics import roc_auc_score

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import REPO_ROOT, fit_catboost, load_dataset, load_params, three_way_split  # noqa: E402

N_PERMUTATIONS = 20
DOCS = REPO_ROOT / "docs"


def main() -> None:
    from catboost import CatBoostClassifier

    params = load_params()
    ds = load_dataset(params)
    split = three_way_split(ds.y, params)
    x_tr, x_va, x_te = ds.x.iloc[split.train], ds.x.iloc[split.val], ds.x.iloc[split.test]
    y_te = ds.y.iloc[split.test].to_numpy()

    shipped = CatBoostClassifier()
    shipped.load_model(str(REPO_ROOT / params["output"]["model_path"]))
    p_shipped = shipped.predict_proba(x_te)[:, 1]

    cfg = params["models"]["catboost"]
    rows = []
    for seed in range(N_PERMUTATIONS):
        y_perm = ds.y.iloc[np.random.default_rng(seed).permutation(len(ds.y))].set_axis(ds.y.index)
        model = fit_catboost(x_tr, y_perm.iloc[split.train], x_va, y_perm.iloc[split.val], ds.cat_cols,
                             {**cfg, "seed": seed})
        p = model.predict_proba(x_te)[:, 1]
        control = np.random.default_rng(1000 + seed).permutation(p)
        rows.append({
            "seed": seed,
            "trees": int(model.tree_count_),
            "auc_vs_true_labels": float(roc_auc_score(y_te, p)),
            "spearman_with_shipped_model": float(spearmanr(p, p_shipped)[0]),
            "control_auc_scores_reassigned": float(roc_auc_score(y_te, control)),
        })
        print(f"  permutation {seed}: AUC {rows[-1]['auc_vs_true_labels']:.3f}, "
              f"rho {rows[-1]['spearman_with_shipped_model']:+.3f}", flush=True)

    auc = np.array([r["auc_vs_true_labels"] for r in rows])
    ctl = np.array([r["control_auc_scores_reassigned"] for r in rows])
    rho = np.array([r["spearman_with_shipped_model"] for r in rows])
    n1, n0 = int(y_te.sum()), int(len(y_te) - y_te.sum())
    summary = {
        "n_permutations": N_PERMUTATIONS,
        "permuted_model_auc": {"mean": float(auc.mean()), "sd": float(auc.std(ddof=1)),
                               "min": float(auc.min()), "max": float(auc.max())},
        "control_auc": {"mean": float(ctl.mean()), "sd": float(ctl.std(ddof=1)),
                        "min": float(ctl.min()), "max": float(ctl.max())},
        # Hanley-McNeil-style null SD for scores independent of labels
        "null_sd_independent_scores": float(np.sqrt((n1 + n0 + 1) / (12 * n1 * n0))),
        "spearman_abs_auc_dev_vs_abs_rho": float(spearmanr(np.abs(auc - 0.5), np.abs(rho))[0]),
        "pearson_auc_vs_rho": float(np.corrcoef(auc, rho)[0, 1]),
        "shipped_model_test_auc": float(roc_auc_score(y_te, p_shipped)),
    }
    out = {"summary": summary, "runs": rows}
    (DOCS / "permutation_check.json").write_text(json.dumps(out, indent=2), encoding="utf-8")

    s = summary
    lines = [
        "# Permutation check: why the degraded candidate's AUC is not 0.5",
        "",
        "Generated by `python model/training/permutation_check.py`. Do not edit by hand.",
        "",
        f"The production recipe was trained on {N_PERMUTATIONS} independent permutations of the churn labels "
        "(train and validation permuted; early stopping on the permuted validation labels) and scored on the "
        "held-out test split against the TRUE labels. Control: the same scores randomly re-assigned to rows.",
        "",
        "| | Mean AUC | SD | Min | Max |",
        "|---|---:|---:|---:|---:|",
        f"| Models trained on permuted labels | {s['permuted_model_auc']['mean']:.3f} | {s['permuted_model_auc']['sd']:.3f} | "
        f"{s['permuted_model_auc']['min']:.3f} | {s['permuted_model_auc']['max']:.3f} |",
        f"| Control: scores independent of rows | {s['control_auc']['mean']:.3f} | {s['control_auc']['sd']:.3f} | "
        f"{s['control_auc']['min']:.3f} | {s['control_auc']['max']:.3f} |",
        "",
        f"Theoretical SD of AUC for label-independent scores on this split: {s['null_sd_independent_scores']:.3f}.",
        "",
        f"Correlation between a permuted model's AUC and the Spearman correlation of its scores with the shipped "
        f"model's scores: {s['pearson_auc_vs_rho']:+.3f} (Pearson, n = {N_PERMUTATIONS}). Rank correlation between "
        f"|AUC - 0.5| and |rho|: {s['spearman_abs_auc_dev_vs_abs_rho']:+.3f}.",
        "",
        "Reading: the permuted-label models are centred on 0.5 (they learned no churn signal), but they spread "
        "far wider than independent scores, and their AUC moves with how much their scores happen to line up with "
        "the real model's. A model fitted to noise is still a function of tenure, charges and contract, which are "
        "strongly predictive, so by chance it can rank churners above or below chance. The demo's degraded "
        "candidate (0.64 after a Platt fit on permuted labels flipped its sign) is within this spread.",
        "",
        "| Seed | Trees | AUC vs true labels | Spearman with shipped model | Control AUC |",
        "|---:|---:|---:|---:|---:|",
    ]
    lines += [f"| {r['seed']} | {r['trees']} | {r['auc_vs_true_labels']:.3f} | {r['spearman_with_shipped_model']:+.3f} | "
              f"{r['control_auc_scores_reassigned']:.3f} |" for r in rows]
    (DOCS / "permutation_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
